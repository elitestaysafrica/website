import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();
const workspaceRoot = path.resolve(projectRoot, '../../..');
const masterclassRoot = path.join(workspaceRoot, 'projects/masterclass');
const outDir = path.join(projectRoot, 'src/app/class/_generated');
const outFile = path.join(outDir, 'content.ts');

const allowedExt = new Set(['.md', '.html']);
const skipDirs = new Set(['node_modules', '.git']);

function walk(dir, base = '') {
  const entries = readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.') || skipDirs.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    const rel = path.join(base, entry.name).replaceAll('\\', '/');
    if (entry.isDirectory()) files.push(...walk(full, rel));
    else if (allowedExt.has(path.extname(entry.name).toLowerCase())) files.push(rel);
  }
  return files;
}

function titleFromMarkdown(content, fallback) {
  const h1 = content.match(/^#\s+(.+)$/m);
  if (h1) return h1[1].replace(/<[^>]+>/g, '').trim();
  return fallback.replace(/[-_]/g, ' ').replace(/\.(md|html)$/i, '').replace(/\b\w/g, c => c.toUpperCase());
}

function excerpt(content) {
  return content
    .replace(/```[\s\S]*?```/g, '')
    .replace(/^#+\s+/gm, '')
    .replace(/[*_`>#-]/g, '')
    .split('\n')
    .map(s => s.trim())
    .filter(Boolean)
    .slice(0, 2)
    .join(' ')
    .slice(0, 220);
}

if (!existsSync(masterclassRoot)) {
  console.warn(`Masterclass source folder not found at ${masterclassRoot}; keeping checked-in generated content.`);
  process.exit(0);
}

const relFiles = walk(masterclassRoot);
const docs = relFiles.map((rel) => {
  const abs = path.join(masterclassRoot, rel);
  const content = readFileSync(abs, 'utf8');
  const ext = path.extname(rel).toLowerCase();
  const slug = rel.replace(/\.(md|html)$/i, '').split('/');
  const stats = statSync(abs);
  return {
    slug,
    path: rel,
    title: titleFromMarkdown(content, path.basename(rel)),
    type: ext.slice(1),
    excerpt: excerpt(content),
    updatedAt: stats.mtime.toISOString(),
    content,
  };
});

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, `// Auto-generated by scripts/generate-masterclass-content.mjs\n// Do not edit by hand.\n\nexport type MasterclassDoc = {\n  slug: string[];\n  path: string;\n  title: string;\n  type: 'md' | 'html';\n  excerpt: string;\n  updatedAt: string;\n  content: string;\n};\n\nexport const masterclassDocs: MasterclassDoc[] = ${JSON.stringify(docs, null, 2)};\n`, 'utf8');
console.log(`Generated ${docs.length} masterclass docs -> ${path.relative(projectRoot, outFile)}`);
